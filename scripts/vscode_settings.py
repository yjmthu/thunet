#!/usr/bin/env python3
"""Write `.vscode/settings.json` so rust-analyzer sees this machine's toolchain.

rust-analyzer runs as its own process: it does not inherit what
`pixi run -e dev -- ...` activates, and its `rust-analyzer.server.extraEnv`
setting expands no `${workspaceFolder}` / `${env:...}` variables (the extension
only stringifies the values). The paths therefore have to be written out
literally, and they differ per platform:

* Windows: `cargo`/`rustc` are in `.pixi/envs/dev/Library/bin`; the MSVC
  linker is found through the registry, so `Path` alone is enough.
* Linux: they are in `.pixi/envs/dev/bin`, and the GTK build scripts behind
  `tray-icon` additionally need the `PKG_CONFIG_PATH` that
  `scripts/activate_linux.sh` exports.

Rather than keeping one settings file per platform, this script is run inside
the environment and copies the activated variables into the workspace
settings:

    pixi run -e dev -- python scripts/vscode_settings.py

The result is generated (and `.vscode/` is git-ignored), so personal tweaks
belong in the user settings rather than in that file.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SETTINGS = ROOT / ".vscode" / "settings.json"

# Variables that change how cargo, rustc and the build scripts behave. Copied
# verbatim when present; everything else (terminal, proxy, user settings) is
# left to the editor.
COPIED = (
  "PATH",
  "CONDA_PREFIX",
  "PKG_CONFIG_PATH",
  "PKG_CONFIG_LIBDIR",
  "LD_LIBRARY_PATH",
  "LIBRARY_PATH",
  "CPATH",
  "CFLAGS",
  "CXXFLAGS",
  "LDFLAGS",
  "CC",
  "CXX",
  "INCLUDE",
  "LIB",
  "LIBPATH",
  "VCINSTALLDIR",
  "VCToolsInstallDir",
  "WindowsSdkDir",
  "DISTUTILS_USE_SDK",
  "MSSdk",
)

HEADER = """\
// GENERATED by `scripts/vscode_settings.py` -- do not edit by hand.
//
// rust-analyzer is a separate process: it cannot see what `pixi run -e dev`
// activates, and its `server.extraEnv` setting expands no VS Code variables.
// This file therefore carries the activated environment of *this* machine
// (Windows `Library/bin`, Linux `bin` plus the GTK `PKG_CONFIG_PATH`), which
// is what makes completion, hover, go-to-definition and diagnostics work
// without having to start the editor from a pixi shell.
//
// Regenerate after moving the checkout or updating the toolchain:
//   pixi run -e dev -- python scripts/vscode_settings.py
"""


def environment() -> dict[str, str]:
  """The activated variables, with `PATH` spelled the way this OS spells it."""
  env = {}
  for name in COPIED:
    value = os.environ.get(name)
    if not value:
      continue
    # Windows keeps `Path` (or whatever case the parent used); using that exact
    # key replaces the variable in the server process instead of adding a
    # second, shadowed copy next to it.
    if name == "PATH":
      key = next((k for k in os.environ if k.upper() == "PATH"), "PATH")
      env[key] = value
    else:
      env[name] = value
  return env


def sysroot() -> Path | None:
  rustc = shutil.which("rustc")
  if rustc is None:
    return None
  out = subprocess.run(
    [rustc, "--print", "sysroot"], capture_output=True, text=True, check=False
  )
  return Path(out.stdout.strip()) if out.returncode == 0 and out.stdout.strip() else None


def settings_text(env: dict[str, str]) -> str:
  settings = {
    "rust-analyzer.server.extraEnv": env,
    # "discover" runs `rustc --print sysroot`, which resolves through `PATH`.
    "rust-analyzer.cargo.sysroot": "discover",
    # `clippy` works here too; `check` keeps diagnostics cheap.
    "rust-analyzer.check.command": "check",
    # Generated trees: never index, watch or search them.
    "rust-analyzer.files.exclude": [".pixi", "target"],
    "files.watcherExclude": {"**/.pixi/**": True, "**/target/**": True},
    "search.exclude": {"**/.pixi": True, "**/target": True},
    "[rust]": {"editor.defaultFormatter": "rust-lang.rust-analyzer"},
  }
  return HEADER + "\n" + json.dumps(settings, indent=2) + "\n"


def main() -> int:
  if not os.environ.get("CONDA_PREFIX") or shutil.which("cargo") is None:
    print(
      "run this inside the environment:\n"
      "  pixi run -e dev -- python scripts/vscode_settings.py",
      file=sys.stderr,
    )
    return 1

  env = environment()
  text = settings_text(env)

  # Standard-library sources: without them rust-analyzer cannot resolve the
  # `core` impls of primitives and reports bogus E0600 errors on `!bool`.
  root = sysroot()
  if root is not None and not (root / "lib/rustlib/src/rust/library").is_dir():
    print(
      f"warning: no standard-library sources under {root}; "
      "add `rust-src` to the dev feature (see pixi.toml)",
      file=sys.stderr,
    )

  if SETTINGS.exists() and SETTINGS.read_text(encoding="utf-8") == text:
    print(f"{SETTINGS.relative_to(ROOT)} is up to date")
    return 0
  SETTINGS.parent.mkdir(parents=True, exist_ok=True)
  SETTINGS.write_text(text, encoding="utf-8", newline="\n")
  print(f"wrote {SETTINGS.relative_to(ROOT)}")
  print(f"  cargo: {shutil.which('cargo')}")
  print(f"  rustc: {shutil.which('rustc')}")
  print(f"  vars:  {', '.join(sorted(env))}")
  return 0


if __name__ == "__main__":
  raise SystemExit(main())
